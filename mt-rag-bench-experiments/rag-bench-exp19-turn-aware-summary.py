import json
import time
import asyncio
from datetime import datetime
import dspy
from dspy.streaming import StreamListener

# =============================================================================
# EXPERIMENT 19 — Turn-aware history summarisation
#
# Failure-mode-driven: exp-4 score per turn drops from 4.04 (T1) to 3.18 (T9).
# That's exactly the regime where the conversation history grows linearly with
# turns and starts to drown the relevant signal. Truncating to last-2 (exp-14)
# helps but loses long-range context.
#
# This experiment mixes both: keep the last 2 turns verbatim, *summarise*
# everything older into one short paragraph. The summary is generated by the
# same LM in a separate call; the answer module sees:
#   - summary_of_earlier_turns (1 short paragraph)
#   - last_2_turns             (verbatim)
#   - context, question
#
# Single variable changed vs exp-15 baseline pipeline: history representation
# is "summary + last-2" instead of "last-2 only". Triggers only when there
# are more than 2 prior turns (no-op for early turns).
# =============================================================================

FILE_PATH  = 'mtrag-human/generation_tasks/reference+RAG.jsonl'
MODEL_NAME = 'my-qwen-9b-fast:latest'
LIMIT      = 300

print(f"Initialising DSPy with Ollama ({MODEL_NAME})...")
qwen_lm = dspy.LM(
    f'ollama_chat/{MODEL_NAME}',
    api_base='http://localhost:11434',
    api_key='ollama',
    cache=False,
    max_tokens=1000,
)
summary_lm = dspy.LM(
    f'ollama_chat/{MODEL_NAME}',
    api_base='http://localhost:11434',
    api_key='ollama',
    cache=False,
    max_tokens=200,
    temperature=0.0,
)
dspy.configure(lm=qwen_lm)


def get_domain(collection: str) -> str:
    col = collection.lower() if isinstance(collection, str) else ''
    if 'fiqa' in col:    return 'finance and investment'
    if 'govt' in col:    return 'government and public policy'
    if 'ibmcloud' in col or 'cloud' in col:
        return 'cloud computing and technical documentation'
    if 'clapnq' in col:  return 'Wikipedia and general knowledge'
    return 'general knowledge'


class SummariseHistory(dspy.Signature):
    """Summarise this conversation history into ONE short paragraph (max 4 sentences)
    capturing only what is relevant for answering follow-up questions: the topic,
    the user's stated goals, key clarifications already established. Drop pleasantries
    and details the assistant has already answered fully."""

    history = dspy.InputField(desc="Conversation turns (User: ... / Assistant: ...).")
    summary = dspy.OutputField(desc="One short paragraph (max 4 sentences). Plain prose.")


class TurnAwareRAGAnswer(dspy.Signature):
    """You are an expert AI assistant. Answer the user's question based ONLY on
    the provided context passages. Do not use any outside knowledge.

    Use the summary of earlier turns to maintain long-range context, and the
    verbatim last-2 turns for immediate continuity.

    CRITICAL RULE: If the context does not contain sufficient information to
    answer the question, you MUST respond with exactly:
    "I cannot answer this question based on the provided documents."
    """

    domain                    = dspy.InputField()
    context                   = dspy.InputField(desc="Numbered reference passages.")
    summary_of_earlier_turns  = dspy.InputField(desc="One-paragraph summary, or 'No earlier turns.'")
    last_2_turns              = dspy.InputField(desc="Up to 2 most recent turns verbatim, or 'No history.'")
    question                  = dspy.InputField()

    answer = dspy.OutputField(
        desc="1-3 sentence answer based strictly on the context. "
             "If insufficient, respond exactly: "
             "'I cannot answer this question based on the provided documents.'"
    )


summarise = dspy.Predict(SummariseHistory)
rag_module = dspy.ChainOfThought(TurnAwareRAGAnswer)

listeners = [
    StreamListener(signature_field_name="reasoning", allow_reuse=True),
    StreamListener(signature_field_name="answer",    allow_reuse=True),
]
streaming_rag = dspy.streamify(rag_module, stream_listeners=listeners)


def build_history_split(inputs):
    """Return (summary_text, last2_text). Older turns get summarised."""
    prior = inputs[:-1]
    if not prior:
        return "No earlier turns.", "No history."
    last2 = prior[-2:]
    older = prior[:-2]

    last2_text = "\n".join(
        f"{t['speaker'].capitalize()}: {t['text']}"
        for t in last2 if isinstance(t, dict) and t.get('text')
    ) or "No history."

    if not older:
        return "No earlier turns.", last2_text

    older_text = "\n".join(
        f"{t['speaker'].capitalize()}: {t['text']}"
        for t in older if isinstance(t, dict) and t.get('text')
    )
    try:
        with dspy.context(lm=summary_lm):
            s = summarise(history=older_text)
        summary_text = str(s.summary).strip() or "No earlier turns."
    except Exception:
        summary_text = older_text[:400]
    return summary_text, last2_text


async def process_single_task(domain, context, summary_text, last2_text, question):
    output_stream = streaming_rag(
        domain=domain,
        context=context,
        summary_of_earlier_turns=summary_text,
        last_2_turns=last2_text,
        question=question,
    )
    final_prediction = None
    async for chunk in output_stream:
        if type(chunk).__name__ == "Prediction":
            final_prediction = chunk
        elif type(chunk).__name__ == "StreamResponse":
            if chunk.chunk:
                print(chunk.chunk, end="", flush=True)
    print()
    return final_prediction


async def run_benchmark_async():
    with open(FILE_PATH, "r", encoding="utf-8") as f:
        data = [json.loads(line) for line in f]

    tasks = data[:LIMIT] if LIMIT else data
    results = []
    print(f"Starting turn-aware RAG benchmark for {len(tasks)} tasks...\n")

    for index, item in enumerate(tasks):
        collection   = item.get('Collection', '')
        domain       = get_domain(collection)
        raw_contexts = item.get("contexts", [])
        if isinstance(raw_contexts, list) and raw_contexts:
            context = "\n\n".join(
                f"[{i+1}] {c.get('text', str(c)) if isinstance(c, dict) else str(c)}"
                for i, c in enumerate(raw_contexts)
            )
        else:
            context = "No context provided."

        inputs = item.get("input", [])
        orig_question = inputs[-1].get("text", "No question") if inputs else "No question"
        rewritten = item.get("rewritten_query", "").strip()
        question = rewritten if rewritten else orig_question

        summary_text, last2_text = build_history_split(inputs)

        targets = item.get("targets", [])
        correct_answer = targets[0].get("text", "No reference") if targets else "No reference"

        print(f"=== {index+1}/{len(tasks)} | Turn {item.get('turn', '?')} | {domain} ===")
        print(f"Q: {question}")
        if summary_text != "No earlier turns.":
            print(f"  [Summarised earlier turns] {summary_text[:120]}{'...' if len(summary_text) > 120 else ''}")

        start = time.time()
        model_answer    = "ERROR"
        model_reasoning = ""
        try:
            result = await asyncio.wait_for(
                process_single_task(domain, context, summary_text, last2_text, question),
                timeout=300.0,
            )
            model_reasoning = str(getattr(result, "reasoning", "")).strip()
            raw = getattr(result, "answer", None)
            model_answer = str(raw).strip() if raw and str(raw).strip().lower() != "none" else "Answer not extractable."
        except asyncio.TimeoutError:
            model_answer = "ERROR: Timeout"
        except Exception as e:
            model_answer = f"ERROR: {e}"

        duration = round(time.time() - start, 2)
        print(f"Duration: {duration}s\n")

        results.append({
            "qid":             item.get("task_id", f"task_{index}"),
            "question":        question,
            "original_question": orig_question,
            "correct_answer":  correct_answer,
            "duration_sec":    duration,
            "model_reasoning": model_reasoning,
            "model_answer":    model_answer,
            "domain":          domain,
            "turn":            item.get("turn", 0),
            "summary_of_earlier_turns": summary_text,
            "last_2_turns":            last2_text,
            "answerability":   (item.get("Answerability", ["?"])[0]
                                if isinstance(item.get("Answerability"), list)
                                else item.get("Answerability", "?")),
        })

    timestamp = datetime.now().strftime("%Y%m%d_%H%M")
    output_file = f"qwen_rag_answers_exp19_turn_aware_summary_{timestamp}.json"
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=4, ensure_ascii=False)

    print(f"=== Done ===")
    print(f"Processed: {len(results)} tasks")
    print(f"Saved to:  {output_file}")


if __name__ == "__main__":
    asyncio.run(run_benchmark_async())
